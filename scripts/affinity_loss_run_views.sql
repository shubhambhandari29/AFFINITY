CREATE OR ALTER VIEW dbo.Affinity_Loss_Run_Claims
AS
WITH ReportParameters AS (
    SELECT CONVERT(date,
        SYSUTCDATETIME() AT TIME ZONE 'UTC' AT TIME ZONE 'Eastern Standard Time'
    ) AS ReportDate
), LAST_DRIVER AS (SELECT CCNT.CLM_NBR, MAX(CCNT.CLM_CNTCT_KEY) LAST_DRIVER_KEY FROM CLM_LakeHouse.dbo.DW_CLMS_CLM_CNTCT_DIMNSN CCNT WHERE CCNT.CURR_VERSN_IND = 'Y' AND CCNT.INVLV_PARTY_ROLE_CD = 'ID' AND UPPER(CCNT.CLM_CNTCT_ROLE_CD) = 'DRIVER' GROUP BY CCNT.CLM_NBR),
     LAST_TXN AS (SELECT FF.CLM_NBR, FF.CLM_FTR_NBR, MAX(FF.FTR_KEY) LAST_FTR_KEY,MAX(FF.LOSS_TXN_PRCSS_DT_DIMKEY) LAST_TXN_PRCSS_DT_DIMKEY FROM CLM_LakeHouse.dbo.DW_FINCL_LOSS_FTR_SS_F FF GROUP BY FF.CLM_NBR, FF.CLM_FTR_NBR),
     EXPENSE_TRANSACTIONS AS (SELECT TXN.CLM_NBR,TXN.CLM_FTR_NBR,
                               SUM(CASE WHEN UPPER(TXN.LOSS_TXN_TYPE_DESC) LIKE '%EXPENSE%' AND
                                             UPPER(TXN.LOSS_TXN_TYPE_DESC) NOT LIKE '%RECOVERY%' THEN
                                             TXN.CLM_TXN_AMT ELSE 0 END) AS EXPENSE,
                               SUM(CASE WHEN UPPER(TXN.LOSS_TXN_TYPE_DESC) LIKE '%EXPENSE%' AND
                                             UPPER(TXN.LOSS_TXN_TYPE_DESC) LIKE '%RECOVERY%' THEN
                                             TXN.CLM_TXN_AMT ELSE 0 END) AS EXPENSE_RECOVERY
                                             FROM CLM_LakeHouse.dbo.DW_FINCL_LOSS_TXN_SS_F TXN GROUP BY TXN.CLM_NBR,TXN.CLM_FTR_NBR),

     LAST_FTR_VERSN AS (SELECT F.CLM_NBR, F.CLM_FTR_NBR, MAX(F.VERSN_BEG_DT) LAST_VERSN FROM CLM_LakeHouse.dbo.DW_CLMS_FTR_DIMNSN F GROUP BY F.CLM_NBR, F.CLM_FTR_NBR),
     LAST_LGL AS (SELECT LF.CLM_KEY, LF.FTR_KEY, MAX(LF.CLMS_LGL_KEY) LAST_CLMS_LGL_KEY FROM CLM_LakeHouse.dbo.DW_CLMS_LGL_FACT LF WHERE LF.EFF_IND = 1 GROUP BY LF.CLM_KEY, LF.FTR_KEY),
     DATA AS (SELECT
           LFIN.CLM_NBR,
           FD.CLM_FTR_NBR,
           LFIN.LAST_TXN_PRCSS_DT_DIMKEY,
           POL.PMS_CUSTMR_NBR,
           POL.POL_NAMED_INSRD_TXT,
           POL.POL_SYM,
           POL.POL_NBR,
           POL.POL_MOD,
           CAST(POL.POL_EFF_DT AS date) POL_EFF_DT,
           CAST(POL.POL_EXP_DT AS date) POL_EXP_DT,
           POL.PRDCNG_AGNT_CD,
           RPA.CUR_PA_FULL_NM,
           CD.CLM_KEY,
           CASE WHEN UPPER(CD.POL_HLDR_CLM_NBR) = 'TRUE' THEN '' ELSE CD.POL_HLDR_CLM_NBR END POL_HLDR_CLM_NBR,
           CD.ACCT_LOSS_LOC_ID,
           CAST(CD.DT_OF_LOSS AS date) DT_OF_LOSS,
           LFINCL.MAJ_PERIL_CD,
           RMP.MAJ_PERIL_DESC,
           LD.LITGTN_STATUS_CD,
           LD.LITGTN_STATUS_DESC,
           CASE WHEN CD.ACDNT_ST_ABBR <>'!' THEN ISNULL(CD.ACDNT_ST_ABBR, cd.CLM_JRSDTN_ST_ABBR)
ELSE cd.CLM_JRSDTN_ST_ABBR END ACDNT_ST_ABBR,
           CLMNT.CLMNT_FULL_NM,
           CLMNT.CLMNT_FIRST_NM,
           CLMNT.CLMNT_LAST_NM,
           CLMNT.CLMNT_CO_NM,
           ISNULL(CLMNT.OCUPTN_TXT, ' ') OCUPTN_TXT,
           LFINCL.CLM_DRVR_KEY,
           DRVD.DRV_REL_TO_INSURED_CODE,
           CONCAT(LDRVD.CLM_CNTCT_FIRST_NM, ' ', LDRVD.CLM_CNTCT_LAST_NM) AS INSURED_DRIVER,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN ISNULL(VD.VEH_TOTL_LOSS_IND, 'N') END AS VEH_TOTL_LOSS_IND,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN VD.VEH_YEAR END AS VEH_YEAR,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN VD.VEH_MANUFACTURER_CODE END AS VEH_MANUFACTURER_CODE,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN VD.VEH_MODEL END AS VEH_MODEL,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN VD.VEH_VIN_NUMBER END AS VEH_VIN_NUMBER,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN VD.VEH_LICENSE_PLATE END AS VEH_LICENSE_PLATE,
           CASE WHEN UPPER(VD.INVLV_VEH_TYPE_CD) = 'INSURED' THEN VD.VEH_REGISTERED_STATE_ABBR END AS VEH_REGISTERED_STATE_ABBR,
           UPPER(FD.FTR_ASGNED_USER_FULL_NM) FTR_ASGNED_USER_FULL_NM,
           UPPER(FD.FTR_ASGN_USER_EMAIL_ADDR) FTR_ASGN_USER_EMAIL_ADDR,
           FD.FTR_ASGN_USER_PHONE_NBR,
           CASE WHEN CD.CLM_LOB_CD='wc' THEN CD.AIA_POSTNS_1_AND_2_DESC ELSE CD.CAUSE_OF_LOSS END AS CAUSE_OF_LOSS,
           CASE WHEN CD.CLM_LOB_CD='wc' THEN CD.AIA_POSTNS_3_AND_4_DESC ELSE CD.LOSS_DESC END AS LOSS_DESC,
           CASE WHEN CD.CLM_LOB_CD='wc' THEN CD.AIA_POSTNS_5_AND_6_DESC ELSE CD.CONTRIBUTING_FCTR END AS CONTRIBUTING_FCTR,
           CD.MF_PRODT_DESC,
           CD.MF_DESC,
           CD.POL_HLDR_RGN_DESC,
           CD.POL_HLDR_RETAILER_DESC,
           CD.CLM_RPTD_DT,
           CD.CLM_STATUS,
           CD.CLM_CLOSE_DT,
           CD.RCRD_SRC_CD,
           CD.INCID_RPT_IND,
           DATENAME(WEEKDAY, CD.DT_OF_LOSS) AS DAY_DT_OF_LOSS,
           FD.EXPOSR_IND,
           FD.FTR_TYPE_CD,
           FD.FTR_TYPE_DESC,
           FD.FTR_COVG_TYPE_CD,
           FD.FTR_COVG_TYPE_DESC,
           ISNULL(FINCL.FTR_CHNG_IN_OSLS_AMT, 0) FTR_CHNG_IN_OSLS_AMT,
           ISNULL(FINCL.FTR_PDLS_INCL_SLVG_SUBRO_AMT, 0) FTR_PDLS_INCL_SLVG_SUBRO_AMT,
           ISNULL(FINCL.FTR_SLVG_AMT, 0) FTR_SLVG_AMT,
           ISNULL(FINCL.FTR_SUBRO_AMT, 0) FTR_SUBRO_AMT,
           ISNULL(FINCL.LOSS_RECOVRY_AMT,0) LOSS_RECOVRY_AMT,
           ISNULL(FINCL.DEDTBL_RECOVRY_AMT, 0) DEDTBL_RECOVRY_AMT,
           ISNULL(FINCL.FTR_ALAE_AMT, 0) FTR_ALAE_AMT,
           ISNULL(ETXN.EXPENSE,0) AS EXPENSE,
           ISNULL(ETXN.EXPENSE_RECOVERY,0) AS EXPENSE_RECOVERY,

           ISNULL(FINCL.FTR_ALAE_AMT-FINCL.expnse_recovry_amt, 0) FTR_ALAE_AMT2,
           ISNULL(FINCL.expnse_recovry_amt, 0) expnse_recovry_amt,
           ISNULL(FINCL.FTR_INCUR_INCL_SLVG_SUBRO_AMT, 0) FTR_INCUR_INCL_SLVG_SUBRO_AMT,
           ISNULL(FINCL.FTR_PDLS_EXCL_SLVG_SUBRO_AMT, 0) FTR_PDLS_EXCL_SLVG_SUBRO_AMT,
           FD.CURR_VERSN_IND
         FROM
           LAST_TXN LFIN
           INNER JOIN CLM_LakeHouse.dbo.DW_FINCL_LOSS_FTR_SS_F LFINCL ON LFIN.CLM_NBR = LFINCL.CLM_NBR AND LFIN.CLM_FTR_NBR = LFINCL.CLM_FTR_NBR AND LFIN.LAST_TXN_PRCSS_DT_DIMKEY = LFINCL.LOSS_TXN_PRCSS_DT_DIMKEY
           INNER JOIN CLM_LakeHouse.dbo.DW_CLMS_CLM_DIMNSN CD ON LFIN.CLM_NBR = CD.CLM_NBR AND CD.CURR_VERSN_IND = 'Y'
           LEFT OUTER JOIN LAST_FTR_VERSN LV ON LFIN.CLM_NBR = LV.CLM_NBR AND LFIN.CLM_FTR_NBR = lv.CLM_FTR_NBR
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_FTR_DIMNSN FD ON LFIN.CLM_NBR = FD.CLM_NBR AND LFIN.CLM_FTR_NBR = FD.CLM_FTR_NBR AND FD.CURR_VERSN_IND = 'Y' AND CAST(FD.VERSN_BEG_DT AS date) = CAST(lv.last_VERSN AS date)

           INNER JOIN CLM_LakeHouse.dbo.DW_POL_DIMNSN POL ON CD.POL_SYM = POL.POL_SYM AND CD.POL_NBR = POL.POL_NBR AND CD.POL_MOD = POL.POL_MOD AND POL.POL_CURR_VERSN_IND = 'Y'
           LEFT OUTER JOIN LAST_LGL LL ON LFINCL.CLM_KEY = LL.CLM_KEY AND LFINCL.FTR_KEY = LL.FTR_KEY
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_LGL_FACT LF ON LFINCL.FTR_KEY = LF.FTR_KEY AND LFINCL.CLM_KEY = LF.CLM_KEY AND LF.CLMS_LGL_KEY = LL.LAST_CLMS_LGL_KEY
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_LGL_DIMNSN LD ON LF.CLMS_LGL_KEY = LD.CLMS_LGL_KEY
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DM_RETNTN_PRDCNG_AGNT_HR_D RPA ON POL.PRDCNG_AGNT_CD = RPA.CUR_ENTR_PA_CD

           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_CLMNT_DIMNSN CLMNT ON LFINCL.CLMNT_KEY = CLMNT.CLMNT_KEY
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_DRVR_DIMNSN DRVD ON LFINCL.CLM_DRVR_KEY = DRVD.CLM_DRVR_KEY
           LEFT OUTER JOIN LAST_DRIVER LDRD ON LFINCL.CLM_NBR = LDRD.CLM_NBR
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_CLM_CNTCT_DIMNSN LDRVD ON LDRVD.CLM_NBR = LDRD.CLM_NBR AND LDRVD.CLM_CNTCT_KEY = LDRD.LAST_DRIVER_KEY
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_CLMS_VEH_DIMNSN VD ON LFINCL.VEH_KEY = VD.VEH_DIMKEY AND VD.CURR_VERSN_IND = 'Y'
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_REF_MAJ_PERIL RMP ON LFINCL.MAJ_PERIL_CD = RMP.MAJ_PERIL_CD AND CAST(LFINCL.RCRD_INSRT_DT AS date) BETWEEN CAST(RMP.VERSN_BEG_DT AS date) AND CAST(RMP.VERSN_END_DT AS date)
           LEFT OUTER JOIN CLM_LakeHouse.dbo.DW_FINCL_LOSS_FTR_SS_F FINCL ON LFINCL.CLM_NBR = FINCL.CLM_NBR AND LFINCL.CLM_FTR_NBR = FINCL.CLM_FTR_NBR
           LEFT OUTER JOIN EXPENSE_TRANSACTIONS ETXN ON LFINCL.CLM_NBR = ETXN.CLM_NBR AND LFINCL.CLM_FTR_NBR = ETXN.CLM_FTR_NBR

WHERE
UPPER(ISNULL(CD.ACCT_LOSS_LOC_ID, 'NA')) NOT LIKE '%REKEY%' AND
ISNULL(CD.INCID_RPT_IND, 'N') = 'N' AND
ISNULL(FD.EXPOSR_IND, 'N') = 'N'




)
SELECT
  D.PMS_CUSTMR_NBR AS [Customer Number],
  D.POL_NAMED_INSRD_TXT AS [Policy Insured Name],
  D.ACCT_LOSS_LOC_ID AS [Account Location Identifier],
  D.POL_SYM AS [Policy Symbol],
  D.POL_NBR AS [Policy Number],
  D.POL_MOD AS [Policy MOD],
  CONCAT(D.POL_SYM, '-', D.POL_NBR, '-', D.POL_MOD) AS [Policy],
  D.POL_EFF_DT AS [Policy Effective Date],
  YEAR(D.POL_EFF_DT) AS [Policy Year],
  D.POL_EXP_DT AS [Policy Expiration Date],
  D.POL_HLDR_CLM_NBR AS [Policy Holder Claim Number],
  D.PRDCNG_AGNT_CD AS [Producing Agent Code],
  D.CUR_PA_FULL_NM AS [Producing Agent Name],
  D.CLM_NBR AS [Claim Number],
  D.CLM_FTR_NBR AS [Exposure],
  CONCAT(D.CLM_NBR, D.CLM_FTR_NBR) AS [Claim Feature Number],


  D.FTR_COVG_TYPE_DESC AS [Coverage],
  D.DT_OF_LOSS AS [Loss Date],
  D.ACDNT_ST_ABBR AS [Accident State],
  SUM(D.FTR_CHNG_IN_OSLS_AMT) AS [Current Loss Reserve],
  (SUM(D.FTR_PDLS_INCL_SLVG_SUBRO_AMT)-sum(d.DEDTBL_RECOVRY_AMT)) AS [Paid Loss Net Salvage Subro],
  (SUM(d.FTR_INCUR_INCL_SLVG_SUBRO_AMT)-sum(d.DEDTBL_RECOVRY_AMT)) AS [Total Incurred],
  CASE WHEN SUM(D.FTR_INCUR_INCL_SLVG_SUBRO_AMT) > 25000 THEN 1 ELSE 0 END AS [Claims above 25K],


  CASE WHEN ISNULL(sum(D.FTR_ALAE_AMT2), 0) = 0 THEN SUM(D.FTR_ALAE_AMT) ELSE sum(D.FTR_ALAE_AMT2) END AS [Total Expense],
  SUM(D.FTR_SLVG_AMT) AS [Salvage Recovery],
  SUM(D.FTR_SUBRO_AMT) AS [Subro Recovery],
  SUM(D.LOSS_RECOVRY_AMT) AS [Loss Recovery],
  SUM(d.DEDTBL_RECOVRY_AMT) AS [Deductible Recovery],
  (SUM(D.FTR_SLVG_AMT)+SUM(D.FTR_SUBRO_AMT)+SUM(D.DEDTBL_RECOVRY_AMT)) AS [Recoveries],
  SUM(D.FTR_ALAE_AMT) AS [Total ALAE Amount],
  ISNULL(sum(D.FTR_ALAE_AMT2), 0) AS [Expense Column],
  MAX(D.EXPENSE) AS [Expense TXN],
  sum(D.EXPENSE_RECOVERY) AS [Expense Recovery TXN],
  ISNULL(sum(D.expnse_recovry_amt), 0)  AS [Expense_Recovery],
  D.LITGTN_STATUS_DESC AS [Litigation Status],
  D.CAUSE_OF_LOSS AS [Cause Of Loss],
  D.LOSS_DESC AS [Description Of Loss],
  D.CONTRIBUTING_FCTR AS [Contributing Factor],
  D.MF_PRODT_DESC AS [Product],
  D.MF_DESC AS [Manufacturer],
  D.POL_HLDR_RGN_DESC AS [Policy Region Description],
  D.POL_HLDR_RETAILER_DESC AS [Policy Holder Retailer Desc],
  D.CLM_RPTD_DT AS [Date of Notice (Report Date)],
  D.CLM_STATUS AS [Claim Status],
  D.CLM_CLOSE_DT AS [Claim Closed Date],
  CONCAT(D.CLMNT_FULL_NM, D.CLMNT_CO_NM) AS [Claimant Name - Company],
  D.CLMNT_FIRST_NM,
  D.CLMNT_LAST_NM,
  D.CLMNT_FULL_NM,
  D.CLMNT_CO_NM,
  D.OCUPTN_TXT AS [Occupation],
  D.DAY_DT_OF_LOSS AS [Accident Day Of Week],
  D.INSURED_DRIVER AS [Insured Driver],
  D.VEH_TOTL_LOSS_IND AS [Total Loss Indicator],
  D.VEH_YEAR AS [Vehicle Year],
  D.VEH_MANUFACTURER_CODE AS [Vehicle Manufacturer],
  D.VEH_MODEL AS [Vehicle Model],
  D.VEH_VIN_NUMBER AS [Vehicle ID Number],
  D.VEH_LICENSE_PLATE AS [Vehicle License Plate],
  D.VEH_REGISTERED_STATE_ABBR AS [Vehicle License State],
  D.FTR_ASGNED_USER_FULL_NM AS [Adjuster],
  D.FTR_ASGN_USER_EMAIL_ADDR AS [Adjuster Email],
  D.FTR_ASGN_USER_PHONE_NBR AS [Adjuster Phone Number],
  D.RCRD_SRC_CD AS [Record Source Code],
  D.INCID_RPT_IND AS [Record Only Indicator],
  D.EXPOSR_IND AS [Exposure Indicator],
  D.CURR_VERSN_IND [Current Version IND],
  (SELECT ReportDate FROM ReportParameters) AS [System Date]
FROM
DATA D
GROUP BY
  D.PMS_CUSTMR_NBR,
  D.POL_NAMED_INSRD_TXT,
  D.ACCT_LOSS_LOC_ID,
  D.POL_SYM,
  D.POL_NBR,
  D.POL_MOD,
  D.POL_EFF_DT,
  D.POL_EXP_DT,
  D.POL_HLDR_CLM_NBR,
  D.PRDCNG_AGNT_CD,
  D.CUR_PA_FULL_NM,
  D.CLM_NBR,
  D.CLM_FTR_NBR,
  D.MAJ_PERIL_DESC,
  D.FTR_TYPE_DESC,
  D.FTR_COVG_TYPE_DESC,
  D.DT_OF_LOSS,
  D.ACDNT_ST_ABBR,
  D.LITGTN_STATUS_DESC,
  D.CAUSE_OF_LOSS,
  D.LOSS_DESC,
  D.CONTRIBUTING_FCTR,
  D.MF_PRODT_DESC,
  D.MF_DESC,
  D.POL_HLDR_RGN_DESC,
  D.POL_HLDR_RETAILER_DESC,
  D.CLM_RPTD_DT,
  D.CLM_STATUS,
  D.CLM_CLOSE_DT,
  CONCAT(D.CLMNT_FULL_NM, D.CLMNT_CO_NM),
  D.CLMNT_FIRST_NM,
  D.CLMNT_LAST_NM,
  D.CLMNT_FULL_NM,
  D.CLMNT_CO_NM,
  D.OCUPTN_TXT,
  D.DAY_DT_OF_LOSS,
  D.INSURED_DRIVER,
  d.CLM_DRVR_KEY,
  d.DRV_REL_TO_INSURED_CODE,
  D.VEH_TOTL_LOSS_IND,
  D.VEH_YEAR,
  D.VEH_MANUFACTURER_CODE,
  D.VEH_MODEL,
  D.VEH_VIN_NUMBER,
  D.VEH_LICENSE_PLATE,
  D.VEH_REGISTERED_STATE_ABBR,
  D.FTR_ASGNED_USER_FULL_NM,
  D.FTR_ASGN_USER_EMAIL_ADDR,
  D.FTR_ASGN_USER_PHONE_NBR,
  D.RCRD_SRC_CD,
  D.INCID_RPT_IND,
  D.EXPOSR_IND,
  d.CURR_VERSN_IND
HAVING
  ((D.CLM_STATUS in ('Closed','closed') AND YEAR(D.POL_EFF_DT) >=YEAR(DATEADD(MONTH, -60, (SELECT ReportDate FROM ReportParameters))))
  OR SUM(D.FTR_CHNG_IN_OSLS_AMT) > 0
  OR D.CLM_STATUS in ('Open','open'))
;
GO

CREATE OR ALTER VIEW dbo.Affinity_Loss_Run_RecordOnly
AS
WITH ReportParameters AS (
    SELECT CONVERT(date,
        SYSUTCDATETIME() AT TIME ZONE 'UTC' AT TIME ZONE 'Eastern Standard Time'
    ) AS ReportDate
), DATA
     AS (SELECT
           CD.CLM_NBR,
           FD.CLM_FTR_NBR,
           NULL AS LAST_TXN_PRCSS_DT_DIMKEY ,
           POL.PMS_CUSTMR_NBR,
           POL.POL_NAMED_INSRD_TXT,
           POL.POL_SYM,
           POL.POL_NBR,
           POL.POL_MOD,
           CAST(POL.POL_EFF_DT AS date) POL_EFF_DT,
           CAST(POL.POL_EXP_DT AS date) POL_EXP_DT,
           POL.PRDCNG_AGNT_CD,
           RPA.CUR_PA_FULL_NM,
           CD.CLM_KEY,
           CASE
             WHEN UPPER(CD.POL_HLDR_CLM_NBR) = 'TRUE' THEN ''
             ELSE CD.POL_HLDR_CLM_NBR
           END
             POL_HLDR_CLM_NBR,
           CD.ACCT_LOSS_LOC_ID,
           CASE WHEN CD.ACDNT_ST_ABBR <> '!' THEN ISNULL(CD.ACDNT_ST_ABBR, CD.CLM_JRSDTN_ST_ABBR)
                ELSE CD.CLM_JRSDTN_ST_ABBR END AS ACDNT_ST_ABBR,
           CAST(CD.DT_OF_LOSS AS date) DT_OF_LOSS,
           FD.FTR_ASGNED_USER_FULL_NM,
           FD.FTR_ASGN_USER_EMAIL_ADDR,
           FD.FTR_ASGN_USER_PHONE_NBR,
           CD.CAUSE_OF_LOSS,
           CD.LOSS_DESC,
           CD.CONTRIBUTING_FCTR,
           CD.MF_PRODT_DESC,
           CD.MF_DESC,
           CD.POL_HLDR_RGN_DESC,
           CD.POL_HLDR_RETAILER_DESC,
           CD.CLM_RPTD_DT,
           CD.CLM_STATUS,
           CD.CLM_CLOSE_DT,
           CD.RCRD_SRC_CD,
           CD.INCID_RPT_IND,
           DATENAME(WEEKDAY, CD.DT_OF_LOSS) AS DAY_DT_OF_LOSS,
           FD.EXPOSR_IND,
           FD.FTR_TYPE_CD,
           FD.FTR_TYPE_DESC,
           FD.FTR_COVG_TYPE_CD,
           FD.FTR_COVG_TYPE_DESC,
           CLMNT.CLMNT_FULL_NM,
           CLMNT.CLMNT_CO_NM,
           ISNULL(CLMNT.OCUPTN_TXT, ' ') OCUPTN_TXT
